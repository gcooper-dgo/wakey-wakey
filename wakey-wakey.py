# Define the key press function
def press_key(hexKeyCode):
    ctypes.windll.user32.keybd_event(hexKeyCode, 0, 0, 0)
    ctypes.windll.user32.keybd_event(hexKeyCode, 0, 2, 0)

today:date = date.today()

quitting_time = (14, 30) # 2:30 pm

this_year = today.year
next_year = today.year + 1


oct31:date = date.fromisoformat(f'{this_year}-10-31')
xmas:date = date.fromisoformat(f'{this_year}-12-25')
if today > oct31: 
    oct31 = f'{next_year}-10-31'
if today > xmas:
    xmas = f'{next_year}-12-25'  
days_till_oct31 = (oct31 - today).days
days_till_xmas = (xmas - today).days


print(f"Only {days_till_oct31} days till Halloween!")
if days_till_oct31 == 0:
    print(' . . . Hey, that\'s today!')
print(f"Only {days_till_xmas} days till Christmas!")

while True:
    now:time = (datetime.now().hour, datetime.now().minute)
    if now < quitting_time:
        press_key(0x91)  # Press the Scroll Lock key
        sleep(180)   # Wait for 3 minutes
    else:  
        print("It's past 2:30. You can go home now!")
